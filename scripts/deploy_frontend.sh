#!/bin/bash

set -e

REPO_URL=$1
S3_BUCKET=$2
API_URL=$3
COGNITO_AUTHORITY=$4
COGNITO_CLIENT_ID=$5
COGNITO_REDIRECT_URI=$6
COGNITO_LOGOUT_URI=$7
COGNITO_AUTH_DOMAIN=$8
AWS_REGION=$9

REPO_NAME=$(basename "$REPO_URL" .git)
CLONE_DIR="frontends/$REPO_NAME"

if [ -d "$CLONE_DIR" ]; then
  echo "Repository already cloned. Skipping clone."
else
  git clone "$REPO_URL" "$CLONE_DIR"
fi

cd "$CLONE_DIR"

cat > .env << EOF
VITE_API_URL=${API_URL}
VITE_ADMIN_COGNITO_AUTHORITY=${COGNITO_AUTHORITY}
VITE_ADMIN_COGNITO_CLIENT_ID=${COGNITO_CLIENT_ID}
VITE_ADMIN_COGNITO_REDIRECT_URI=${COGNITO_REDIRECT_URI}
VITE_ADMIN_COGNITO_LOGOUT_URI=${COGNITO_LOGOUT_URI}
VITE_ADMIN_COGNITO_AUTH_DOMAIN=${COGNITO_AUTH_DOMAIN}
VITE_S3_BUCKET_NAME=${S3_BUCKET}
VITE_AWS_REGION=${AWS_REGION}
VITE_PROBLEMS_START_DATE="2026-06-01T09:00:00+08:00"
VITE_PROBLEMS_SELECTION_DATE="2026-06-01T09:00:00+08:00"
VITE_PROBLEMS_SELECTION_END_DATE="2026-06-15T23:59:00+08:00"
VITE_HACKATHON_START_DATE="2026-06-07T09:00:00+08:00"
VITE_SUBMISSION_START_DATE="2026-06-09T09:00:00+08:00"
VITE_SUBMISSION_END_DATE="2026-06-12T23:59:00+08:00"
VITE_FEEDBACK_RELEASE_DATE="2026-06-15T17:00:00+08:00"
VITE_FINALISTS_ANNOUNCEMENT_DATE="2026-06-15T17:00:00+08:00"
VITE_WINNERS_ANNOUNCEMENT_DATE="2026-06-15T17:00:00+08:00"
VITE_SHOW_SCORE=0
VITE_FINAL_SUBMISSION_START_DATE="2026-06-09T09:00:00+08:00"
VITE_FINAL_SUBMISSION_END_DATE="2026-06-12T23:59:00+08:00"
VITE_ENABLE_SCORING_DATETIME_CONTROL=1
VITE_SCORING_START_DATE="2026-06-12T00:00:00+08:00"
VITE_SCORING_END_DATE="2026-06-14T23:59:00+08:00"
VITE_SCORING_LOCK_DATE="2026-06-15T00:00:00+08:00"
EOF

npm install
npm run build

aws s3 sync dist/ "s3://${S3_BUCKET}/" --delete
